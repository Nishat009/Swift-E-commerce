// Lists every route that creates, changes or deletes data, with the guard it actually has.
//   node scripts/routeReport.js            print the markdown table
//   node scripts/routeReport.js --write    update the table in ../SECURITY.md
// tests/route-guards.test.js uses collectMutatingRoutes() and checks SECURITY.md is up to date.
const fs = require('fs');
const path = require('path');

process.env.JWT_SECRET ||= 'route-report-placeholder-secret-0123456789';
process.env.JWT_REFRESH_SECRET ||= 'route-report-placeholder-refresh-0123456789';
const { protect } = require('../src/middleware/authMiddleware');
const { requireSuperAdmin } = require('../src/middleware/roleMiddleware');
const { blockDemoAdmin } = require('../src/controllers/demoAuthController');
const { PUBLIC, requiredAccess } = require('../src/config/routePolicy');

const SRC = path.join(__dirname, '..', 'src');
const ROUTES_DIR = path.join(SRC, 'routes');
const SECURITY_MD = path.join(__dirname, '..', '..', 'SECURITY.md');
const START = '<!-- route-table:start (generated by backend/scripts/routeReport.js, do not edit by hand) -->';
const END = '<!-- route-table:end -->';

// "cartRoutes.js" -> "cart"
const routerName = (file) => file.replace(/Routes\.js$/, '');

// Mount path of each route file, read from app.js: app.use('/api/cart', cartRoutes)
const mountPaths = () => {
  const app = fs.readFileSync(path.join(SRC, 'app.js'), 'utf8');
  const variableToFile = Object.fromEntries([...app.matchAll(/const (\w+) = require\('\.\/routes\/(\w+)'\)/g)].map((m) => [m[1], `${m[2]}.js`]));
  return Object.fromEntries([...app.matchAll(/app\.use\('([^']+)', (\w+)\)/g)]
    .filter((m) => variableToFile[m[2]])
    .map((m) => [variableToFile[m[2]], m[1]]));
};

// Line of `router.<method>('<path>'` in the route file
const lineOf = (source, method, routePath) => {
  const needle = `router.${method}('${routePath}'`;
  const index = source.split(/\r?\n/).findIndex((line) => line.includes(needle));
  return index + 1;
};

/** Every POST/PUT/PATCH/DELETE route with its guards, policy and source location. */
const collectMutatingRoutes = () => {
  const mounts = mountPaths();
  const routes = [];
  for (const file of fs.readdirSync(ROUTES_DIR).filter((f) => f.endsWith('.js')).sort()) {
    const router = require(path.join(ROUTES_DIR, file));
    const source = fs.readFileSync(path.join(ROUTES_DIR, file), 'utf8');
    const name = routerName(file);
    let routerProtect = false;
    let routerRoles = [];
    for (const layer of router.stack) {
      if (!layer.route) {
        // router.use(...) applies to every route declared after it
        if (layer.handle === protect) routerProtect = true;
        if (layer.handle.roles) routerRoles = layer.handle.roles;
        continue;
      }
      const handles = layer.route.stack.map((s) => s.handle);
      for (const method of Object.keys(layer.route.methods).filter((m) => !['get', 'head', '_all'].includes(m))) {
        const key = `${name} ${method.toUpperCase()} ${layer.route.path}`;
        routes.push({
          name,
          key,
          method: method.toUpperCase(),
          url: `${mounts[file] || '?'}${layer.route.path === '/' ? '' : layer.route.path}`,
          file: `backend/src/routes/${file}`,
          line: lineOf(source, method, layer.route.path),
          protect: routerProtect || handles.includes(protect),
          roles: [...routerRoles, ...handles.flatMap((h) => h.roles || [])],
          superAdmin: handles.includes(requireSuperAdmin),
          demoBlocked: handles.includes(blockDemoAdmin) || handles.includes(requireSuperAdmin),
          access: requiredAccess(key, name),
        });
      }
    }
  }
  return routes;
};

const guardText = (route) => {
  if (!route.protect) return `public: ${PUBLIC[route.key] || 'NOT IN POLICY'}`;
  const parts = ['`protect`'];
  if (route.roles.length) parts.push(`\`authorize('${route.roles.join("', '")}')\``);
  if (route.superAdmin) parts.push('`requireSuperAdmin`');
  else if (route.demoBlocked) parts.push('`blockDemoAdmin`');
  if (!route.roles.length) parts.push('own records only');
  return parts.join(' + ');
};

const markdownTable = (routes = collectMutatingRoutes()) => {
  const counts = routes.reduce((acc, r) => ({ ...acc, [r.access]: (acc[r.access] || 0) + 1 }), {});
  const rows = routes
    .slice()
    .sort((a, b) => a.url.localeCompare(b.url) || a.method.localeCompare(b.method))
    .map((r) => `| ${r.method} | \`${r.url}\` | ${guardText(r)} | [${path.basename(r.file)}:${r.line}](${r.file}#L${r.line}) |`);
  return [
    `${routes.length} routes that create, change or delete data: ${counts.admin || 0} admin-only, ${counts['signed-in'] || 0} for signed-in users (own records), ${counts.public || 0} public by design.`,
    '',
    '| Method | Route | Guard | Defined at |',
    '| :--- | :--- | :--- | :--- |',
    ...rows,
  ].join('\n');
};

/** SECURITY.md with the generated table between the markers replaced. */
const securityDocWithTable = (doc, table = markdownTable()) => {
  const start = doc.indexOf(START);
  const end = doc.indexOf(END);
  if (start < 0 || end < start) throw new Error('SECURITY.md has no route-table markers');
  return `${doc.slice(0, start + START.length)}\n${table}\n${doc.slice(end)}`;
};

if (require.main === module) {
  if (process.argv.includes('--write')) {
    const doc = fs.readFileSync(SECURITY_MD, 'utf8').replace(/\r\n/g, '\n');
    fs.writeFileSync(SECURITY_MD, securityDocWithTable(doc));
    console.log('SECURITY.md route table updated.');
  } else {
    console.log(markdownTable());
  }
  process.exit(0);
}

module.exports = { collectMutatingRoutes, markdownTable, securityDocWithTable, SECURITY_MD };
